function build_hpipm_mex(hpipm_root,blasfeo_root)
% Build the official OCP-QP wrappers locally; never write into vendor trees.
if nargin<1, hpipm_root='D:\Tools\hpipm'; end
if nargin<2, blasfeo_root='D:\Tools\blasfeo'; end
here=fileparts(mfilename('fullpath')); out=fullfile(here,'mex');
if ~exist(out,'dir'), mkdir(out); end
diary(fullfile(here,'build_log.txt')); guard=onCleanup(@()diary('off'));
assert(~isempty(mex.getCompilerConfigurations('C','Selected')),'No selected MEX C compiler');
src=fullfile(hpipm_root,'interfaces','matlab_octave');
names={'ocp_qp_dim_create','ocp_qp_dim_destroy','ocp_qp_dim_set', ...
 'ocp_qp_create','ocp_qp_destroy','ocp_qp_set','ocp_qp_get', ...
 'ocp_qp_sol_create','ocp_qp_sol_destroy','ocp_qp_sol_get','ocp_qp_sol_set', ...
 'ocp_qp_solver_arg_create','ocp_qp_solver_arg_destroy','ocp_qp_solver_arg_set', ...
 'ocp_qp_solver_create','ocp_qp_solver_destroy','ocp_qp_solver_solve','ocp_qp_solver_get'};
setenv('PATH',[fullfile(hpipm_root,'build') pathsep fullfile(blasfeo_root,'build') pathsep getenv('PATH')]);
for k=1:numel(names)
 fprintf('BUILD %s\n',names{k});
 mex('-R2018a',['-I' fullfile(hpipm_root,'include')], ...
  ['-I' fullfile(blasfeo_root,'include')],fullfile(hpipm_root,'build','libhpipm.dll.a'), ...
  fullfile(blasfeo_root,'build','libblasfeo.dll.a'), ...
  fullfile(src,[names{k} '.c']),'-outdir',out);
end
fprintf('HPIPM_MEX_BUILD_PASS count=%d\n',numel(names));
mex('-R2018a',['-I' fullfile(hpipm_root,'include')], ...
 ['-I' fullfile(blasfeo_root,'include')],fullfile(hpipm_root,'build','libhpipm.dll.a'), ...
 fullfile(blasfeo_root,'build','libblasfeo.dll.a'),fullfile(here,'hpipm_qp_read.c'),'-outdir',out);
end
